//! Private fixed-row runs: bounded sort buffers and bounded merge fan-in.
//! Used for construction catalogs, never as an unchecked public file decoder.
use anyhow::{ensure, Result};
use std::{
    cmp::Reverse,
    collections::BinaryHeap,
    fs::File,
    io::{BufReader, BufWriter, Read, Write},
    marker::PhantomData,
    path::{Path, PathBuf},
    sync::{atomic::AtomicBool, Arc},
};
const FAN_IN: usize = 32;
const IO_BUFFER: usize = 4096;

pub(crate) trait Row: Copy + Ord + Send + Sync {
    const WIDTH: usize;
    fn write(self, out: &mut impl Write) -> Result<()>;
    fn decode(bytes: &[u8]) -> Self;
}
impl Row for u64 {
    const WIDTH: usize = 8;
    fn write(self, out: &mut impl Write) -> Result<()> {
        out.write_all(&self.to_le_bytes())?;
        Ok(())
    }
    fn decode(bytes: &[u8]) -> Self {
        u64::from_le_bytes(bytes[..8].try_into().unwrap())
    }
}
fn next<T: Row>(input: &mut impl Read) -> Result<Option<T>> {
    // Catalog row widths are small and fixed; reject partial rows.
    ensure!(
        T::WIDTH <= 32 && T::WIDTH > 0,
        "Invalid construction row width"
    );
    let mut bytes = [0; 32];
    if input.read(&mut bytes[..1])? == 0 {
        return Ok(None);
    }
    input.read_exact(&mut bytes[1..T::WIDTH])?;
    Ok(Some(T::decode(&bytes[..T::WIDTH])))
}

pub(crate) struct Sorter<'a, T: Row> {
    owner: Arc<tempfile::TempDir>,
    buffer: Vec<T>,
    limit: usize,
    levels: Vec<Vec<PathBuf>>,
    serial: usize,
    unique: bool,
    cancel: &'a AtomicBool,
}
impl<'a, T: Row> Sorter<'a, T> {
    pub fn new(parent: &Path, bytes: usize, unique: bool, cancel: &'a AtomicBool) -> Result<Self> {
        let limit = bytes / std::mem::size_of::<T>();
        ensure!(limit > 0, "Catalog sort budget too small");
        let mut buffer = Vec::new();
        buffer.try_reserve_exact(limit)?;
        Ok(Self {
            owner: Arc::new(
                tempfile::Builder::new()
                    .prefix("catalog-")
                    .tempdir_in(parent)?,
            ),
            buffer,
            limit,
            levels: Vec::new(),
            serial: 0,
            unique,
            cancel,
        })
    }
    fn path(&mut self) -> PathBuf {
        let path = self.owner.path().join(format!("{}.run", self.serial));
        self.serial += 1;
        path
    }
    pub fn push(&mut self, value: T) -> Result<()> {
        if self.buffer.len() % 4096 == 0 {
            super::disk_edges::check(self.cancel)?;
        }
        self.buffer.push(value);
        if self.buffer.len() == self.limit {
            self.flush()?;
        }
        Ok(())
    }
    fn flush(&mut self) -> Result<()> {
        if self.buffer.is_empty() {
            return Ok(());
        }
        super::disk_edges::check(self.cancel)?;
        self.buffer.sort_unstable();
        if self.unique {
            self.buffer.dedup();
        }
        let path = self.path();
        let mut out = BufWriter::with_capacity(IO_BUFFER, super::disk_edges::create(&path)?);
        for &row in &self.buffer {
            row.write(&mut out)?;
        }
        out.flush()?;
        drop(out);
        self.buffer.clear();
        self.promote(path, 0)
    }
    fn merge(&mut self, inputs: Vec<PathBuf>) -> Result<PathBuf> {
        ensure!(inputs.len() <= FAN_IN, "Catalog merge fan-in exceeded");
        let path = self.path();
        let mut readers: Vec<_> = inputs
            .iter()
            .map(|p| File::open(p).map(|f| BufReader::with_capacity(IO_BUFFER, f)))
            .collect::<std::io::Result<_>>()?;
        let mut out = BufWriter::with_capacity(IO_BUFFER, super::disk_edges::create(&path)?);
        let mut heap = BinaryHeap::new();
        for (slot, reader) in readers.iter_mut().enumerate() {
            if let Some(row) = next::<T>(reader)? {
                heap.push(Reverse((row, slot)));
            }
        }
        let mut previous = None;
        let mut count = 0usize;
        while let Some(Reverse((row, slot))) = heap.pop() {
            if count % 4096 == 0 {
                super::disk_edges::check(self.cancel)?;
            }
            count += 1;
            if !self.unique || previous != Some(row) {
                row.write(&mut out)?;
            }
            previous = Some(row);
            if let Some(row) = next::<T>(&mut readers[slot])? {
                heap.push(Reverse((row, slot)));
            }
        }
        out.flush()?;
        drop(out);
        drop(readers);
        // Only paths generated by this sorter in its private temporary directory.
        for input in inputs {
            std::fs::remove_file(input)?;
        }
        Ok(path)
    }
    fn promote(&mut self, path: PathBuf, level: usize) -> Result<()> {
        if self.levels.len() == level {
            self.levels.push(Vec::new());
        }
        self.levels[level].push(path);
        if self.levels[level].len() == FAN_IN {
            let inputs = std::mem::take(&mut self.levels[level]);
            let merged = self.merge(inputs)?;
            self.promote(merged, level + 1)?;
        }
        Ok(())
    }
    pub fn finish(mut self) -> Result<MappedRows<T>> {
        self.flush()?;
        let mut runs: Vec<_> = std::mem::take(&mut self.levels)
            .into_iter()
            .flatten()
            .collect();
        if runs.is_empty() {
            let path = self.path();
            super::disk_edges::create(&path)?;
            runs.push(path);
        }
        while runs.len() > 1 {
            let mut merged = Vec::new();
            for group in runs.chunks(FAN_IN) {
                merged.push(self.merge(group.to_vec())?);
            }
            runs = merged;
        }
        MappedRows::open(&runs[0], self.owner.clone())
    }
}

#[derive(Clone, Debug)]
pub(crate) struct MappedRows<T: Row> {
    // Drop the mapping before releasing the owning directory (Windows included).
    bytes: Option<Arc<memmap2::Mmap>>,
    count: usize,
    _owner: Arc<tempfile::TempDir>,
    marker: PhantomData<T>,
}
impl<T: Row> MappedRows<T> {
    pub fn open(path: &Path, owner: Arc<tempfile::TempDir>) -> Result<Self> {
        let file = File::open(path)?;
        let length = usize::try_from(file.metadata()?.len())?;
        ensure!(length % T::WIDTH == 0, "Partial construction catalog row");
        let bytes = if length == 0 {
            None
        } else {
            // Private completed spool; its writer is closed before mapping.
            Some(Arc::new(unsafe { memmap2::Mmap::map(&file)? }))
        };
        Ok(Self {
            bytes,
            count: length / T::WIDTH,
            _owner: owner,
            marker: PhantomData,
        })
    }
    pub fn len(&self) -> usize {
        self.count
    }
    pub fn get(&self, index: usize) -> T {
        assert!(index < self.count);
        let offset = index * T::WIDTH;
        T::decode(&self.bytes.as_ref().unwrap()[offset..offset + T::WIDTH])
    }
    pub fn iter(&self) -> impl Iterator<Item = T> + '_ {
        (0..self.count).map(|i| self.get(i))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn tiny_bounded_runs_merge_deduplicate_and_keep_full_width_ids() {
        let dir = tempfile::tempdir().unwrap();
        let cancel = AtomicBool::new(false);
        let mut sorter = Sorter::new(dir.path(), 16, true, &cancel).unwrap();
        let mut expected = vec![0, u64::MAX, 1u64 << 48];
        expected.extend((0..6000).map(|i| i * 17));
        for &value in expected.iter().rev() {
            sorter.push(value).unwrap();
            sorter.push(value).unwrap();
        }
        let rows = sorter.finish().unwrap();
        expected.sort_unstable();
        expected.dedup();
        assert_eq!(rows.iter().collect::<Vec<_>>(), expected);
    }
    #[test]
    fn cancellation_and_duplicate_policy_are_explicit() {
        let dir = tempfile::tempdir().unwrap();
        let cancel = AtomicBool::new(false);
        let mut sorter = Sorter::new(dir.path(), 32, false, &cancel).unwrap();
        for value in [9u64, 3, 9] {
            sorter.push(value).unwrap();
        }
        assert_eq!(
            sorter.finish().unwrap().iter().collect::<Vec<_>>(),
            vec![3, 9, 9]
        );
        cancel.store(true, std::sync::atomic::Ordering::Relaxed);
        assert!(Sorter::<u64>::new(dir.path(), 32, true, &cancel)
            .unwrap()
            .push(1)
            .is_err());
        assert!(next::<u64>(&mut &b"short"[..]).is_err());
    }
}
